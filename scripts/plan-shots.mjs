// Screenshots of the Type A1 plan with the preset furniture. Dev server on 5300.
import { chromium } from 'playwright';
import { existsSync } from 'node:fs';
const chrome = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome';
const browser = await chromium.launch({ executablePath: existsSync(chrome) ? chrome : undefined, headless: true });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage();
const PLAN = process.env.PLAN || 'a1';
const errors = [];
page.on('pageerror', (e) => errors.push(e.message));
page.on('console', (m) => { if (m.type() === 'error' && !m.text().includes('404')) errors.push(m.text()); });
await page.goto(process.argv[2] || 'http://localhost:5300');
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForFunction(() => window.planner?.ready);
await page.selectOption('#layout', PLAN);
await page.waitForFunction((id) => window.planner.state.layout === id && window.planner.ready, PLAN);
await page.waitForTimeout(400);
await page.click('#addAll');
await page.evaluate(() => window.planner.select(null));
const shot = (n) => page.waitForTimeout(600).then(() => page.screenshot({ path: `shots/${PLAN}-${n}.png` }));
await shot('3d');
await page.click('#viewTop');
await shot('top');
await page.click('#drawing');
await shot('top-nodrawing');
await page.click('#viewTop'); await page.click('#view3d');
await page.click('#lowWalls');
await page.evaluate(() => { const p = window.planner; p.orbit.target.set(0, 0, 0); p.persp.position.set(9, 12, 14); });
await shot('fullwalls');
const st = await page.evaluate(() => { const p = window.planner; const s = p.evaluate(); return p.state.items.map((i) => `${i.type}:${s.get(i.id)}`); });
console.log(st.join(' '));
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
